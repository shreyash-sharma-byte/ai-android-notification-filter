#!/usr/bin/env bash
#
# Builds a signed NotifyCleaner APK with no Gradle, no Android Studio and no root.
# Requires only a JDK plus an Android SDK (see tools/install-sdk.sh).
#
set -euo pipefail
cd "$(dirname "$0")"

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/android-sdk}}"
BUILD_TOOLS_VERSION="${BUILD_TOOLS_VERSION:-35.0.0}"
PLATFORM="${PLATFORM:-android-35}"
BT="$SDK/build-tools/$BUILD_TOOLS_VERSION"
AJ="$SDK/platforms/$PLATFORM/android.jar"

for tool in aapt2 d8 zipalign apksigner; do
  if [ ! -x "$BT/$tool" ]; then
    echo "ERROR: $BT/$tool not found. Run tools/install-sdk.sh first." >&2
    exit 1
  fi
done
if [ ! -f "$AJ" ]; then
  echo "ERROR: $AJ not found. Run tools/install-sdk.sh first." >&2
  exit 1
fi

PKG=io.github.shreyashsharmabyte.notifycleaner
APP=NotifyCleaner

# Single source of truth for the version: the manifest.
VERSION_NAME=$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' AndroidManifest.xml | head -1)
VERSION_CODE=$(sed -n 's/.*android:versionCode="\([^"]*\)".*/\1/p' AndroidManifest.xml | head -1)
MIN_SDK=$(sed -n 's/.*android:minSdkVersion="\([0-9]*\)".*/\1/p' AndroidManifest.xml | head -1)
TARGET_SDK=$(sed -n 's/.*android:targetSdkVersion="\([0-9]*\)".*/\1/p' AndroidManifest.xml | head -1)

for v in "$VERSION_NAME" "$VERSION_CODE" "$MIN_SDK" "$TARGET_SDK"; do
  if [ -z "$v" ]; then
    echo "ERROR: could not read version/sdk values from AndroidManifest.xml" >&2
    exit 1
  fi
done

echo "== NotifyCleaner $VERSION_NAME ($VERSION_CODE), sdk $MIN_SDK..$TARGET_SDK =="

# The logic harness runs first: an APK is never produced from a tree whose decision,
# retry or escaping tests fail. SKIP_TESTS=1 bypasses it deliberately.
if [ "${SKIP_TESTS:-0}" != "1" ]; then
  echo "== logic tests =="
  ./test.sh
fi

OUT=build
rm -rf "$OUT"
mkdir -p "$OUT/res" "$OUT/classes" "$OUT/dex" "$OUT/gen/$PKG"

# ---------------------------------------------------------------- 1. BuildConfig
# AGP generates this class; without Gradle we emit the same shape by hand.
cat > "$OUT/gen/$PKG/BuildConfig.java" <<EOF
package $PKG;

/** Generated by build.sh from AndroidManifest.xml. Do not edit. */
public final class BuildConfig {
    public static final String VERSION_NAME = "$VERSION_NAME";
    public static final int VERSION_CODE = $VERSION_CODE;

    private BuildConfig() {}
}
EOF

# ---------------------------------------------------------------- 2. Resources
echo "== aapt2 compile =="
"$BT/aapt2" compile --dir res -o "$OUT/res/resources.zip"

echo "== aapt2 link =="
"$BT/aapt2" link \
  -o "$OUT/unsigned.apk" \
  -I "$AJ" \
  --manifest AndroidManifest.xml \
  -R "$OUT/res/resources.zip" \
  -A assets \
  --min-sdk-version "$MIN_SDK" \
  --target-sdk-version "$TARGET_SDK" \
  --version-code "$VERSION_CODE" \
  --version-name "$VERSION_NAME" \
  --auto-add-overlay

# ---------------------------------------------------------------- 3. Java
echo "== javac =="
find src "$OUT/gen" -name '*.java' > "$OUT/sources.txt"
javac --release 8 -nowarn -Xlint:-options -cp "$AJ" -d "$OUT/classes" @"$OUT/sources.txt"

# ---------------------------------------------------------------- 4. Dex
echo "== d8 =="
find "$OUT/classes" -name '*.class' > "$OUT/classes.txt"
"$BT/d8" --release --min-api "$MIN_SDK" --lib "$AJ" --output "$OUT/dex" @"$OUT/classes.txt"

# ---------------------------------------------------------------- 5. Package dex
APK_ABS="$(pwd)/$OUT/unsigned.apk"
( cd "$OUT/dex" && zip -q -X "$APK_ABS" classes.dex )

# ---------------------------------------------------------------- 6. Align
echo "== zipalign =="
"$BT/zipalign" -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

# ---------------------------------------------------------------- 7. Sign
KS=release.jks
KS_PASS="${KS_PASS:-android}"
KS_ALIAS="${KS_ALIAS:-notifycleaner}"

if [ ! -f "$KS" ]; then
  echo "== creating $KS =="
  echo "   This key identifies your builds. Keep it, back it up, never commit it."
  echo "   Android will only accept updates to this app that are signed with it."
  keytool -genkeypair \
    -keystore "$KS" -storepass "$KS_PASS" -keypass "$KS_PASS" \
    -alias "$KS_ALIAS" -keyalg RSA -keysize 4096 -validity 10000 \
    -dname "CN=Notify Cleaner, OU=Android, O=Notify Cleaner, C=IN"
fi

echo "== apksigner =="
"$BT/apksigner" sign \
  --ks "$KS" --ks-key-alias "$KS_ALIAS" \
  --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" \
  --v4-signing-enabled false \
  --out "$OUT/$APP-$VERSION_NAME.apk" "$OUT/aligned.apk"

"$BT/apksigner" verify --print-certs "$OUT/$APP-$VERSION_NAME.apk"

SIZE=$(du -h "$OUT/$APP-$VERSION_NAME.apk" | cut -f1)
echo
echo "Built $OUT/$APP-$VERSION_NAME.apk ($SIZE)"
